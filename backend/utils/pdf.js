const PDFDocument = require('pdfkit');

module.exports = function buildReport(res, { user, prediction }) {
  const doc = new PDFDocument({ margin: 50 });
  doc.pipe(res);
  const pretty = (s) => s.replace(/_/g, ' ');

  doc.fontSize(20).fillColor('#0f4c45').text('AI Medical Assistant - Health Report');
  doc.moveDown(0.3).fontSize(10).fillColor('#555')
    .text(`Generated: ${new Date().toLocaleString()}   |   Report ID: ${prediction._id}`);
  doc.moveDown().fillColor('#000').fontSize(12);
  doc.text(`Patient: ${user.name}`);
  doc.text(`Age: ${prediction.age ?? '-'}    Gender: ${prediction.gender || '-'}`);
  doc.text(`Date of check: ${new Date(prediction.createdAt).toLocaleString()}`);

  doc.moveDown().fontSize(14).fillColor('#0f4c45').text('Reported symptoms');
  doc.fontSize(12).fillColor('#000').text(prediction.symptoms.map(pretty).join(', '));

  if (prediction.emergency) {
    doc.moveDown().fillColor('#b3261e').fontSize(12)
      .text('EMERGENCY WARNING: You reported symptoms that can be serious (chest pain / breathing trouble). Please visit a hospital or call emergency services now.');
    doc.fillColor('#000');
  }

  doc.moveDown().fontSize(14).fillColor('#0f4c45').text('Possible conditions');
  prediction.results.forEach((r, i) => {
    doc.moveDown(0.6).fontSize(13).fillColor('#000')
      .text(`${i + 1}. ${r.disease} - ${r.probability}% match (severity: ${r.severity})`);
    doc.fontSize(11).fillColor('#333').text(`Consult: ${r.doctor}`);
    doc.text('Medicines / treatment (general info): ' + r.medicines.join('; '));
    doc.text('Precautions: ' + r.precautions.join('; '));
  });

  doc.moveDown(2).fontSize(9).fillColor('#777').text(
    'DISCLAIMER: This report is generated by an AI system for educational and informational purposes only. It is NOT a medical diagnosis and does not replace advice from a qualified doctor. Do not start or stop any medicine without consulting a licensed medical professional.',
    { align: 'justify' });
  doc.end();
};
